// Offline mechanical regeneration; preserve every original font/license byte.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const files = [
  ["vera-regular", "bitstream-vera-sans-regular.ttf", "font/ttf"],
  ["vera-bold", "bitstream-vera-sans-bold.ttf", "font/ttf"],
  ["vera-license", "bitstream-vera-license.txt", "text/plain; charset=utf-8"]
];
const entries = files.map(([id, file, type]) => {
  const bytes = readFileSync(new URL(file, import.meta.url));
  return [id, { file, type, sha256: createHash("sha256").update(bytes).digest("hex"), base64: bytes.toString("base64") }];
});
const header = `/**
 * Generated by fonts/embed.mjs from the original files in fonts/.
 * Bitstream Vera Sans: Copyright (c) 2003 by Bitstream, Inc.
 * The complete accompanying license is embedded as vera-license and retained
 * in fonts/bitstream-vera-license.txt. Do not edit the generated bytes.
 */
export type FontAssetId = "vera-regular" | "vera-bold" | "vera-license";
interface EmbeddedFontAsset {
  readonly file: string;
  readonly type: string;
  readonly sha256: string;
  readonly base64: string;
}
export const embeddedFontAssets: Readonly<Record<FontAssetId, EmbeddedFontAsset>> = `;
writeFileSync(new URL("../font-bytes.ts", import.meta.url), `${header}${JSON.stringify(Object.fromEntries(entries), null, 2)};\n`);
